import { expect } from "@playwright/test";
import { test } from "./fixtures/installation-branding";
import { login } from "./login-helper";
import { checkedPage } from "./fixtures/page-checks";

const widths = [1440, 390, 320];
test.use({ actionTimeout: 15000 });

test("la marca del participante conserva texto, icono y logotipo sin recortes", async ({
  page,
  browser,
  restoreBranding,
}) => {
  test.setTimeout(120000);
  await login(page, "admin");
  await restoreBranding();
  const participant = await browser.newPage({
    baseURL: process.env.E2E_URL ?? "http://localhost:4317",
  });
  try {
    await login(participant, "stakeholder");
    for (const variant of ["default", "logo", "long"] as const) {
      if (variant !== "default") {
        await page.goto("/admin/settings/appearance");
        if (variant === "logo") {
          // A fictional PNG, generated by the browser; no institutional asset.
          const png = await page.evaluate(() => {
            const canvas = document.createElement("canvas");
            canvas.width = 120;
            canvas.height = 40;
            const context = canvas.getContext("2d")!;
            context.fillStyle = "#2b4d7c";
            context.fillRect(0, 0, 120, 40);
            return canvas.toDataURL("image/png").split(",")[1]!;
          });
          await page
            .getByLabel("Subir logotipo principal")
            .setInputFiles({
              name: "example.png",
              mimeType: "image/png",
              buffer: Buffer.from(png, "base64"),
            });
          await page
            .getByRole("button", {
              name: "Guardar logotipo principal",
              exact: true,
            })
            .click();
          await expect(
            page.getByText("Logotipo principal guardado.", { exact: true }),
          ).toBeVisible();
        } else {
          await page
            .getByLabel("Nombre corto", { exact: true })
            .fill("Colaboración de ejemplo");
          await page
            .getByRole("button", { name: "Guardar identidad", exact: true })
            .click();
          await expect(
            page.getByText("Configuración guardada.", { exact: true }),
          ).toBeVisible();
        }
      }
      await participant.goto("/");
      await expect(
        participant.locator(".participant-brand .brand-name"),
      ).toHaveText(variant === "long" ? "Colaboración de ejemplo" : "Acta");
      for (const colorScheme of ["light", "dark"] as const) {
        await participant.emulateMedia({ colorScheme });
        for (const width of widths) {
          await participant.setViewportSize({ width, height: 900 });
          await participant.evaluate(() => document.fonts.ready);
          const brand = participant.locator(".participant-brand");
          const name = brand.locator(".brand-name");
          const metrics = await name.evaluate((el) => ({
            scroll: el.scrollWidth,
            client: el.clientWidth,
          }));
          expect
            .soft(
              metrics.scroll,
              `${variant}/${colorScheme}/${width}: nombre completo`,
            )
            .toBeLessThanOrEqual(metrics.client);
          const box = (await name.boundingBox())!,
            parent = (await brand.boundingBox())!;
          expect.soft(box.x).toBeGreaterThanOrEqual(parent.x);
          expect
            .soft(box.x + box.width)
            .toBeLessThanOrEqual(parent.x + parent.width + 1);
          expect.soft(parent.x + parent.width).toBeLessThanOrEqual(width);
          const icon = (await brand
            .locator("span")
            .filter({ has: participant.locator("svg") })
            .boundingBox())!;
          expect.soft(icon.width).toBe(28);
          expect.soft(icon.height).toBe(28);
          if (variant !== "default")
            await expect(brand.locator("img")).toBeVisible();
          expect
            .soft(
              await participant.evaluate(
                () => document.documentElement.scrollWidth,
              ),
            )
            .toBeLessThanOrEqual(width);
        }
      }
    }
  } finally {
    await participant.close();
  }
});

test("el título recibe foco sin recuadro y Tab conserva el foco visible de los controles", async ({
  page,
}) => {
  test.setTimeout(120000);
  await login(page, "admin");
  const projects = await page.evaluate(() =>
    fetch("/api/v1/projects").then((r) => r.json()),
  );
  const id = projects.find(
    (p: { externalId: string }) => p.externalId === "DEMO-PRINCIPAL",
  ).id;
  for (const path of [
    "/admin",
    "/review",
    `/projects/${id}/invitations`,
    "/admin/settings/appearance",
    `/projects/${id}/import`,
  ]) {
    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: 900 });
      await page.goto(path);
      const heading = page.locator("main h1");
      await expect(heading).toBeFocused();
      expect
        .soft(
          await heading.evaluate((el) => getComputedStyle(el).outlineStyle),
          path,
        )
        .toBe("none");
      await page.keyboard.press("Tab");
      const focus = await page.evaluate(() => {
        const el = document.activeElement!;
        return {
          control: el.matches("a,button,input,select,textarea,summary"),
          visible: el.matches(":focus-visible"),
          shadow: getComputedStyle(el).boxShadow,
        };
      });
      expect(focus.control).toBe(true);
      expect(focus.visible).toBe(true);
      expect(focus.shadow).not.toBe("none");
      await checkedPage(page, "", "heading-focus", width, { capture: false });
    }
  }
});
